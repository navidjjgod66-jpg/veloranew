export const isProduct = id => Object.hasOwn(CATALOG, id);

export function getCatalogEntries(filter = 'all', typeFilter = 'all') {
  let entries = Object.entries(CATALOG);

  if (filter !== 'all') {
    entries = entries.filter(([, product]) => product.kind === filter);
  }

  if (typeFilter !== 'all') {
    entries = entries.filter(([, product]) => product.type === typeFilter);
  }

  return entries;
}

export function getProductRouteId(value = '') {
  const raw = String(value || '').trim();
  if (!raw) return null;

  const hash = raw.includes('#') ? raw.split('#').pop() : raw;
  const match = hash.match(/^(?:\/)?(?:product[-\/])?([a-z0-9_-]+)$/i);
  return match ? match[1] : null;
}

export function buildProductUrl(id, base = 'https://kafshevelora.ir/') {
  const productId = String(id || '').trim();
  if (!productId) return base;

  const next = new URL(base || 'https://kafshevelora.ir/');
  next.hash = `product-${productId}`;
  return next.href;
}

