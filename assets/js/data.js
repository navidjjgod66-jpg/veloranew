/* Deterministic PRNG so a given edition always renders the same artwork. */
function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* Coordinates are quantised to 2dp: the SVG is generated markup that the
   browser has to parse and lay out, and full float precision is invisible. */
const q = n => Math.round(n * 100) / 100;

const ART_CACHE_MAX = 400;
const artCache = new Map();

export function generateArt(pal, shape, seed) {
  /* Artwork is deterministic in (palette, shape, seed): the same SVG string is
     rebuilt on every re-render of the grid. Memoizing turns repeated renders
     into Map lookups; the bound keeps a long filter session from growing the
     cache without limit. */
  const key = pal[0] + '\0' + pal[1] + '\0' + shape + '\0' + seed;
  const cached = artCache.get(key);
  if (cached !== undefined) return cached;

  const rng = mulberry32(seed * 9973 + 42);
  const c = pal[1];
  const out = [];

  if (shape === 'disc') {
    for (let i = 0; i < 24; i++) {
      out.push(
        `<circle cx="200" cy="150" r="${q(28 + rng() * 105)}" stroke="${c}" stroke-opacity="${q(0.08 + rng() * 0.22)}" fill="none" stroke-width="${q(0.4 + rng() * 0.4)}"/>`
      );
    }
  } else if (shape === 'arc') {
    for (let i = 0; i < 18; i++) {
      const r = q(55 + i * 7);
      const start = rng() * Math.PI * 2;
      const len = 0.25 + rng() * 1.3;
      const x1 = q(200 + Math.cos(start) * r),
        y1 = q(150 + Math.sin(start) * r);
      const x2 = q(200 + Math.cos(start + len) * r),
        y2 = q(150 + Math.sin(start + len) * r);
      out.push(
        `<path d="M${x1} ${y1} A${r} ${r} 0 ${len > Math.PI ? 1 : 0} 1 ${x2} ${y2}" stroke="${c}" stroke-opacity="${q(0.12 + rng() * 0.28)}" fill="none" stroke-width="${q(0.5 + rng() * 0.4)}"/>`
      );
    }
  } else {
    for (let i = 0; i < 12; i++) {
      out.push(
        `<rect x="${q(35 + rng() * 70)}" y="${q(18 + i * 22 + rng() * 8)}" width="${q(70 + rng() * 230)}" height="1" fill="${c}" opacity="${q(0.12 + rng() * 0.32)}"/>`
      );
    }
  }
  const art = out.join('');
  if (artCache.size >= ART_CACHE_MAX) artCache.clear();
  artCache.set(key, art);
  return art;
}
