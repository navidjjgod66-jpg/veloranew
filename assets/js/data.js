/* ─── Footwear size engine ───
   Mondopoint (foot length in cm) is the only unambiguous basis, so EU/UK/US
   conversions are deterministic and shared by the size guide, the product
   page fit hint and the custom-foot recommendation. */
const SIZE_TABLE = [
  { eu: 36, mm: 225 },
  { eu: 37, mm: 235 },
  { eu: 38, mm: 245 },
  { eu: 39, mm: 250 },
  { eu: 40, mm: 260 },
  { eu: 41, mm: 265 },
  { eu: 42, mm: 275 },
  { eu: 43, mm: 285 },
  { eu: 44, mm: 290 },
  { eu: 45, mm: 300 },
];

export function sizeFromFootLength(lengthCm) {
  const mm = Number(lengthCm) * 10;
  if (!Number.isFinite(mm) || mm <= 0) return null;
  /* A shoe should be ~5–10mm longer than the foot; pick the first size whose
     internal length covers the foot plus that allowance. */
  const fit = SIZE_TABLE.find(row => row.mm >= mm + 5) || SIZE_TABLE[SIZE_TABLE.length - 1];
  const tightest = SIZE_TABLE.find(row => row.mm >= mm) || fit;
  return { eu: fit.eu, innerMm: fit.mm, footMm: Math.round(mm), tightestEu: tightest.eu };
}

export function euToUk(eu) {
  const uk = Math.round((Number(eu) - 33) * 2) / 2;
  return uk > 0 ? uk : null;
}

export function euToUs(eu) {
  const us = Number(eu) - 31.5;
  return us > 0 ? Math.round(us * 2) / 2 : null;
}

/* CATALOG gains keys only during module init (server prices patch existing
   entries in place), so the entry list is stable after first call — one
   Object.entries allocation for the whole session instead of one per render
   or keystroke of the shop filter. */
let catalogEntries = null;
export function getCatalogEntries(filter = 'all', typeFilter = 'all') {
  if (filter === 'all' && typeFilter === 'all') {
    if (!catalogEntries) catalogEntries = Object.entries(CATALOG);
    return catalogEntries.slice();
  }

  let entries = getCatalogEntries();

  if (filter !== 'all') {
    entries = entries.filter(([, product]) => product.kind === filter);
  }

  if (typeFilter !== 'all') {
    entries = entries.filter(([, product]) => product.type === typeFilter);
  }

  return entries;
}

export function getProductRouteId(value = '') {
  const raw = String(value || '').trim();
  if (!raw) return null;

  const hash = raw.includes('#') ? raw.split('#').pop() : raw;
  const match = hash.match(/^(?:\/)?(?:product[-\/])?([a-z0-9_-]+)$/i);
  return match ? match[1] : null;
}

export function buildProductUrl(id, base = 'https://kafshevelora.ir/') {
  const productId = String(id || '').trim();
  if (!productId) return base;

  const next = new URL(base || 'https://kafshevelora.ir/');
  next.hash = `product-${productId}`;
  return next.href;
}

